    /// Labels indicating that the picture shows food without naming a dish.
    static let genericFoodLabels: Set<String> = ["food", "dessert", "fruit", "vegetable", "baked_goods", "meat", "seafood", "drink", "plate", "bowl", "tableware", "utensil"]

    struct Candidate: Identifiable, Equatable {
        var id: String { label }
        var label: String
        var name: String
        var query: String
        var confidence: Double
    }

    /// Converts raw classifier results into food candidates, best first.
    static func candidates(from observations: [(identifier: String, confidence: Float)],
                           minimumConfidence: Float = 0.08, limit: Int = 6) -> [Candidate] {
        var result: [Candidate] = []
        for obs in observations.sorted(by: { $0.confidence > $1.confidence }) where obs.confidence >= minimumConfidence {
            guard let entry = entries[obs.identifier], !genericFoodLabels.contains(obs.identifier) else { continue }
            if result.contains(where: { $0.query == entry.query }) { continue }
            result.append(Candidate(label: obs.identifier, name: entry.name, query: entry.query, confidence: Double(obs.confidence)))
            if result.count >= limit { break }
        }
        return result
    }

    /// True when the classifier believes the picture contains food at all.
    static func looksLikeFood(_ observations: [(identifier: String, confidence: Float)]) -> Bool {
        observations.contains { ($0.confidence >= 0.1) && (genericFoodLabels.contains($0.identifier) || entries[$0.identifier] != nil) }
    }
}
